"use strict";
// Browser-level regression suite: isolated, no brokerage or network market-data access.
const { chromium, devices } = require("playwright");
const path = require("node:path");
const assert = require("node:assert/strict");
(async () => {
 const browser=await chromium.launch({headless:true});
 const context=await browser.newContext({...devices["iPhone 13"], browserName:undefined});
 const page=await context.newPage();
 const failures=[];
 page.on("pageerror",err=>failures.push(err.message));
 await page.goto("file://"+path.resolve("trident-mobile/index.html"));
 await page.locator("#decision").waitFor();
 assert.equal((await page.locator("#decision").innerText()).trim(),"NO TRADE");
 assert.match(await page.locator("#tradeBadge").innerText(),/停用/);
 await page.getByRole("button",{name:"風控／持倉",exact:true}).click();
 await page.locator("#side").selectOption("LONG");
 await page.locator("#symbol").fill("2330");
 await page.locator("#entry").fill("50");
 await page.locator("#stop").fill("49");
 await page.locator("#target").fill("53");
 await page.locator("#shares").fill("1000");
 await page.getByRole("button",{name:"計算風險"}).click();
 assert.match(await page.locator("#riskResult").innerText(),/1225/);
 await page.locator("#side").selectOption("SHORT");
 await page.locator("#stop").fill("51");
 await page.locator("#target").fill("47");
 await page.getByRole("button",{name:"計算風險"}).click();
 assert.match(await page.locator("#riskResult").innerText(),/1225/);
 await page.locator("#side").selectOption("LONG");
 await page.getByRole("button",{name:"計算風險"}).click();
 assert.match(await page.locator("#riskResult").innerText(),/不合法/);
 await page.getByRole("button",{name:"設定",exact:true}).click();
 const now=new Date().toISOString();
 const fixture={as_of:now,source:"USER-CLAIM-ONLY",coverage:"100% real-time",signals:[{symbol:"2330",name:"測試",side:"WATCH",entry:50,stop:49,target:53}]};
 await page.locator("#file").setInputFiles({name:"test.json",mimeType:"application/json",buffer:Buffer.from(JSON.stringify(fixture))});
 await page.getByRole("button",{name:"匯入並檢查"}).click();
 assert.match(await page.locator("#importStatus").innerText(),/匯入完成/);
 await page.getByRole("button",{name:"總覽",exact:true}).click();
 assert.match(await page.locator("#feedBadge").innerText(),/未認證/);
 assert.match(await page.locator("#coverage").innerText(),/未驗證/);
 assert.equal((await page.locator("#decision").innerText()).trim(),"NO TRADE");
 const color=await page.locator("#feedBadge").evaluate(el=>el.className);
 assert(!color.includes("ok"),"untrusted data must not appear verified");
 const overflow=await page.evaluate(()=>document.documentElement.scrollWidth-innerWidth);
 assert(overflow<=1,"iPhone layout must not overflow horizontally: "+overflow);
 await page.screenshot({path:"trident-iphone-e2e.png",fullPage:true});
 assert.deepEqual(failures,[],"browser JavaScript errors");
 await browser.close();
 console.log("iPhone browser E2E PASS: navigation, LONG/SHORT validation, import trust boundary, NO TRADE, layout");
})().catch(e=>{console.error(e);process.exit(1)});
