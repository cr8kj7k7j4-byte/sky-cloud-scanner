"""Read-only full-market intraday observation, separate from frozen V1.1 alpha.

This module never creates BUY signals. MIS OTC is operational fallback, not
certified TPEx-native realtime coverage. Missing data must remain missing.
"""
from __future__ import annotations

import json
from datetime import datetime, time
from pathlib import Path
from statistics import median
from zoneinfo import ZoneInfo

from .official import fetch_mis_quotes, load_official_universe

OUT = Path("output/swing_v11_market")
TZ = ZoneInfo("Asia/Taipei")


def summarize(universe, quotes, health, warnings, now):
    by_market = {"TWSE": 0, "TPEx": 0}
    for q in quotes:
        if q.get("exchange") in by_market:
            by_market[q["exchange"]] += 1
    valid = [q for q in quotes if isinstance(q.get("change_pct"), (int, float))]
    up = sum(q["change_pct"] > 0 for q in valid)
    down = sum(q["change_pct"] < 0 for q in valid)
    flat = len(valid) - up - down
    spread_known = sum(
        q.get("bid") is not None and q.get("ask") is not None for q in quotes
    )
    coverage = len(quotes) / len(universe) if universe else 0.0
    session = time(9, 0) <= now.time() <= time(13, 30) and now.weekday() < 5
    healthy = bool(
        health.get("twse", 0) >= 500 and health.get("tpex", 0) >= 400
        and by_market["TWSE"] >= 400 and by_market["TPEx"] >= 300
        and coverage >= .80
    )
    return {
        "generated_at": now.isoformat(),
        "scope": "WHOLE_MARKET_INTRADAY_OBSERVATION_ONLY",
        "market_session_window": session,
        "source": "TWSE MIS TSE + OTC operational fallback",
        "strict_tpex_realtime_certified": False,
        "strategy_signal": False,
        "trading_authorized": False,
        "operational_coverage_healthy": healthy,
        "universe_count": len(universe),
        "quote_count": len(quotes),
        "quote_coverage_pct": round(coverage * 100, 2),
        "twse_quotes": by_market["TWSE"],
        "tpex_otc_fallback_quotes": by_market["TPEx"],
        "advancing": up, "declining": down, "unchanged": flat,
        "median_change_pct": round(median([q["change_pct"] for q in valid]), 4) if valid else None,
        "spread_known_count": spread_known,
        "warnings": list(health.get("warnings") or []) + list(warnings),
        "notes": [
            "No V1.1 signal is generated by this observation.",
            "Coverage alone is not proof of quote freshness; market holidays and timestamp gaps must be checked.",
            "OTC MIS quotes are fallback, not TPEx-native certification.",
        ],
    }


def run():
    OUT.mkdir(parents=True, exist_ok=True)
    now = datetime.now(TZ)
    universe, health = load_official_universe()
    quotes, warnings = fetch_mis_quotes(universe)
    report = summarize(universe, quotes, health, warnings, now)
    (OUT / "latest.json").write_text(json.dumps(report, ensure_ascii=False, indent=2), encoding="utf-8")
    lines = [
        f"Sky Swing V1.1 全市場即時觀察｜{now:%Y-%m-%d %H:%M}",
        f"母池 {report['universe_count']}｜報價 {report['quote_count']}｜覆蓋 {report['quote_coverage_pct']}%",
        f"TWSE {report['twse_quotes']}｜OTC(MIS備援) {report['tpex_otc_fallback_quotes']}",
        f"上漲 {report['advancing']}｜下跌 {report['declining']}｜平盤 {report['unchanged']}",
        f"掃描品質 {'合格' if report['operational_coverage_healthy'] else '不足'}｜研究觀察，不產生買進訊號",
    ]
    (OUT / "latest.txt").write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))
    return report


if __name__ == "__main__":
    run()
